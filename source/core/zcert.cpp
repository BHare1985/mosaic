#include <mosaic/core/zcert.h>

#include <fstream>
#include <sstream>

namespace mosaic {
namespace {

    /// The format is INI-ish with quoted values: `    public-key = "..."`. Only the keys we care about are
    /// read; unknown sections and metadata are ignored rather than treated as errors, because the point is
    /// to accept files written by other tools.
    std::optional<std::string> value_of(const std::string& line, const std::string& key)
    {
        const auto equals = line.find('=');
        if (equals == std::string::npos)
            return std::nullopt;
        auto name = line.substr(0, equals);
        const auto first = name.find_first_not_of(" \t");
        const auto last = name.find_last_not_of(" \t");
        if (first == std::string::npos)
            return std::nullopt;
        name = name.substr(first, last - first + 1);
        if (name != key)
            return std::nullopt;

        auto value = line.substr(equals + 1);
        const auto vfirst = value.find_first_not_of(" \t");
        if (vfirst == std::string::npos)
            return std::string { };
        value = value.substr(vfirst);
        if (!value.empty() && value.back() == '\r')
            value.pop_back();
        if (value.size() >= 2 && value.front() == '"' && value.back() == '"')
            value = value.substr(1, value.size() - 2);
        return value;
    }

} // namespace

std::optional<ZcertIdentity> load_zcert(const std::string& path)
{
    std::ifstream in(path);
    if (!in)
        return std::nullopt;

    ZcertIdentity identity;
    std::string line;
    while (std::getline(in, line)) {
        if (line.empty() || line[0] == '#')
            continue;
        if (const auto value = value_of(line, "public-key"))
            identity.public_z85 = *value;
        else if (const auto secret = value_of(line, "secret-key"))
            identity.secret_z85 = *secret;
        else if (const auto name = value_of(line, "name"))
            identity.name = *name;
        else if (const auto email = value_of(line, "email"))
            identity.email = *email;
        else if (const auto organization = value_of(line, "organization"))
            identity.organization = *organization;
    }
    // A certificate without both keys is not a usable identity, so it is rejected rather than
    // half-loaded (the same rule the keystore follows).
    if (identity.public_z85.empty() || identity.secret_z85.empty())
        return std::nullopt;
    return identity;
}

bool save_zcert(const ZcertIdentity& identity, const std::string& path)
{
    if (identity.public_z85.empty() || identity.secret_z85.empty())
        return false;
    std::ofstream out(path, std::ios::trunc);
    if (!out)
        return false;
    out << "#   ****  generated by Mosaic - compatible with ZeroMQ certificate tooling  ****\n"
        << "metadata\n";
    if (!identity.name.empty())
        out << "    name = \"" << identity.name << "\"\n";
    if (!identity.email.empty())
        out << "    email = \"" << identity.email << "\"\n";
    if (!identity.organization.empty())
        out << "    organization = \"" << identity.organization << "\"\n";
    out << "curve\n"
        << "    public-key = \"" << identity.public_z85 << "\"\n"
        << "    secret-key = \"" << identity.secret_z85 << "\"\n";
    return out.good();
}

} // namespace mosaic
